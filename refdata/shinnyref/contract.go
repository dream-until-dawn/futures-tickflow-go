// Package shinnyref 从天勤 openmd 的合约目录里读出【合约参考数据】。
//
// ⛔ 本包**不定接口，交出具体类型**。这不是省事，是 2026-09-10 验过的结论：
//
//	本仓今天用到 refdata 的地方：**0 处**（`grep -rn refdata --include=*.go`，非测试 6 行，
//	而那 6 行全是【注释】—— 其中 3 行还是指向一个已被推翻的出处，已改）
//	⇒ 抽一个**没有第二个实现、也没有调用方**的接口，**它的形状只能来自我的想象**
//	⇒ 而本仓判过两次同一格：「接口只取编排真的会调的那些」「一个零调用点的检查器，
//	  它挡住的东西全在别人的想象里」
//
// ⇒ 抽接口的触发写成**当场可求值**的一句：
// **出现第一个 `import .../refdata/shinnyref` 的包**（今天 0 个 —— 求值法见下面那一节，
// ⚠️ 而**不要用裸的 `grep -rl 'refdata/shinnyref'`**：它今天就会给出一个假的「已到期」）。
//
// —— 谁会用它 ——
//
// **下游的记账内核，经 `adapter`。** 这一句是动手前写死的，而它同时就是字段取舍的判据：
// **只交 refdata 独有的那些，不为想象中的消费者加字段。**
//
//	⛔ 它【不是】给 Syncer 的减法用的（㉒）——那半要【上市日】，而这个上游没有：
//	  全量实测 47 个字段里唯一像日期的只有 expire_datetime（＝到期，不是上市）
//	  ⇒ **refdata 关不掉 ㉔ 与 ㉒**，替代出处见 docs/probe.md「复核 v5」那一节
//	⛔ 到期日那一半本仓也已经有一个够用的出处：`tickflow.Symbol.Expiry()` 是**纯算术**
//	  （从合约代码本身推交割年月，零依赖）⇒ 本包给的是**更精确的那一个**，不是唯一的那一个
//
// —— 字段命名 ——
//
// ⚠️ 字段名与取舍按**本仓的语义**，不是天勤 JSON 的转写。
// 否则每一个消费者都会绑在天勤的形状上，**而那一层本该由本包吃掉**。
//
// # 到期条件（包级，当场可求值）
//
// ⛔ **本包的失败哨兵【一个都不导出】**（decode.go 与 fetch.go 各一个 var 块）。
// 理由是本包对外的失败分类还没有进 docs/contract.md，而本仓的规矩是文档先行。
//
// 而「不导出」今天有一个后果：
//
//	包外调用方【没法 errors.Is 分类】⇒ 「调用方自己按错误分流」这句话**今天只对包内成立**
//	⇒ 到期条件：**在出现第一个包外调用方之前**
//	   求值法（**问编译器，不问文本**）：
//
//	     go list -f '{{range .Imports}}{{.}}
//	     {{end}}{{range .TestImports}}{{.}}
//	     {{end}}' ./... | grep -c 'refdata/shinnyref'
//
//	   本仓两个 go.mod ⇒ **在根目录和 `tools/` 各跑一次**。
//	   读数 —— **今天 0 和 0**（2026-09-10 当场求值）
//
//	⚠️ 这条方法在**两个已知端点**上验过（别的判据都栽在没验这一步上）：
//	   临时造一个 import 本包的包 ⇒ 数到 **1**；撤掉 ⇒ 回到 **0**；
//	   正向对照（根包 `futures-tickflow-go` 被 import 的次数）⇒ **10**，不是常量 0。
//
// ⛔ **【更正】原来这里写的求值法是裸的 `grep -rl 'refdata/shinnyref' --include=*.go .`，
// 而它今天就会给出【一个假的「已到期」】**（评审方 2026-09-10 实测，我复现）：
//
//	裸文本 grep ⇒ 本包之外命中 **1**：`symbol.go:53`
//	              —— 而那是一句**注释**：「…`refdata/shinnyref` 造 Symbol 时…」
//	带引号的 import grep ⇒ 每一颗 SHA 都是 **0**
//
// 🔴 **而让它从 0 变成 1 的，正是写下这条到期条件的【同一颗提交】** ——
// 那句注释和这条求值法是一起写下去的，**所以它生下来就是坏的，而它从来没红过**。
// ⇒ 判据（本仓「命中 ＝ 出处 ＋ 引用」那一族的又一次）：
// **一条到期条件的【求值法】本身也会被写它的那一颗污染
// ⇒ 写完求值法，立刻拿它在【那一颗自己】上跑一次。**
//
// ⛔ **而我照做之后，第一版改法【当场又栽了一次】**：
// 我把它换成 `grep -rn '"<完整 import 路径>"'` —— 而**写下这条方法的那一行本身
// 就含着那个带引号的路径** ⇒ 它命中自己 ⇒ 读数 1，不是 0。
// 🔴 **同一个病高了一层：这一次污染源不是别处的注释，是【方法的定义行】自己。**
// ⇒ 于是判据再收窄一格：**任何「数一数某个字符串出现几次」的求值法，
// 都会把【写下它的那一行】算进去** —— 除非换成一个**不读源文本**的问法。
// ⇒ 所以最终用的是 `go list`：它输出的是 **import 图**，不是注释。
// ⚠️ 而这一格的后果不是「数字难看」：**假的「已到期」会把两个哨兵导出去**，
// 而导出之后再收回来是破坏性变更。
//
// 🔴 **它写在【包级】而不是某一个 var 块上，而这是被咬出来的**（评审方 2026-09-10）：
// 这条到期条件第一次是挂在 decode.go 那个 var 块上的；随后 fetch.go 新加了三个哨兵，
// **它们没有继承那条到期条件** —— 而求值法明明是**包级**的（「有没有本包之外的包」）。
// ⇒ 形状：**一条规矩立在某一处之后，新写的同类地方不会自动继承它。**
// 而它是「立规矩时当场扫一遍【旧的】」那条的**镜像** —— 这次漏的是**新的**。
// ⇒ 处置：**判据的粒度是什么，它就该写在什么粒度上。**
package shinnyref

import (
	"time"

	tickflow "github.com/dream-until-dawn/futures-tickflow-go"
)

// Contract 是一个合约的参考数据。
//
// 字段集刻意小：**只有本仓拿不到别处的那些**，加上一个「更精确的到期时刻」。
// 每一个字段旁边写着它的来历与它的坑 —— 那些坑全部是 2026-09-10 在**全量**
// （7671 条 FUTURE）上量出来的，读数见 docs/design.md 那一节。
type Contract struct {
	// Symbol 是合约。本仓的 Symbol 自带交易所/品种/交割年月，
	// 所以本包**不再单独存** product_id / exchange_id / delivery_year / delivery_month。
	Symbol tickflow.Symbol

	// Multiplier 是一手多少个单位（天勤 volume_multiple）。
	//
	// ✅ 全量 7671/7671 恒在、零值 0 条。而**本仓没有别的出处** —— 它是本包独有的两样之一。
	Multiplier int

	// PriceTick 是最小变动价位。
	//
	// ⚠️ 用 float64，而这是本仓**已定并量过**的那一侧（docs/probe.md 那一节）：
	//
	//	价格与量用 float64 跨库传是安全的；**金额运算必须在 decimal 那一侧做**
	//	实测（拿的正是这个字段当刻度）：float64 → decimal 往返 **29/29 逐位无损**
	//	不无损的是【金额乘法】—— 而本库**绝不预先算任何金额**
	//
	// ⛔ 我曾把这一条推反过（引对了前提，结论写成「要走 decimal」），已更正。
	// 📎 而上游这个字段有**两种 JSON 数字类型**（全量 int 5989 / float 1682）——
	// float64 两种都吃得下，这也是选它的一个附带理由。
	PriceTick float64

	// ExpireTs 是到期时刻，**unix 毫秒**（与 tickflow.Bar.Ts 同单位）。
	//
	// ⚠️ 存的是【时刻】不是【交易日】：把它折成交易日要日历（夜盘属于下一个交易日），
	// 而那是 Calendar 的活，不是本包的。**本包不做它答不了的那一步。**
	ExpireTs int64

	// Sessions 是这个合约的时段表。⚠️ 它的坑不少，全部写在 Sessions 上。
	Sessions Sessions
}

// Sessions 是一个合约的时段表。
//
// ⛔ **对一个【已到期】的合约，上游这份表像是它【最后一天】的快照，
// 不是它一生的标称模板** —— 这是 2026-09-10 量出来的，而它推翻了本仓先前那句
// 「按合约、带年代」的用法：
//
//	年代对得上，是因为**最后一天恰好在那个年代**；
//	而一个最后一天不正常的合约（长假前后、停市期间），它这份表**不代表它一生的模板**
//	⇒ **直接拿它当 IntradayPeriod.Phase 的「标称模板」是不安全的**
type Sessions struct {
	// Day 是日盘时段。全量 7671/7671 都有。
	Day []Range

	// Night 是夜盘那一格，**三态**，见 NightState。
	Night Night
}

// Range 是一个时段，左闭右开。
//
// ⛔ 两端都是【自交易日名义起点起的偏移】，**不是时刻** —— 这一格是实测逼出来的：
//
//	上游把夜盘写成 "21:00:00" ~ "25:00:00" / "26:30:00"（＝次日 01:00 / 02:30）
//	而 time.Parse("15:04:05", "25:00:00") ⇒ **报错 hour out of range**
//
// 🔴 `time.Parse` 拒绝的**不是坏数据，是一个它表达不了的正确值** ——
// 它的目标类型是【时刻】，而这个值是【偏移】。
// ⇒ 判据：**当一个「吵」的检查拦住了正确的输入，先问它检查的是不是【另一个类型】。**
type Range struct {
	Start time.Duration
	End   time.Duration
}

// NightState 是夜盘那一格的三种状态。
//
// ⛔ **三态不许合并**，而理由不是「我不知道」，是**可逆性**：
//
//	保留三态  ⇒ **可逆**：哪天确定了两者同义，合并是免费的
//	合并两态  ⇒ **不可逆**：那个区分在落盘数据里、在此后每一个下游判断里，都没了
//
// 🔴 **不确定时选可逆的那一边** —— 它挡得住那句最常见的反驳
// （「明摆着是一回事，你想多了」）：对「明摆着」，「我不知道」答不上，「改回来免费」答得上。
//
// ⚠️ 而第三态（NightEmpty）的语义**本仓今天不知道**。已知的是一组相关（全量实测）：
//
//	193 条 empty 全部 expired=true 且 open_interest=0 且 pre_volume=0（必要，远不充分）
//	它们只落在 **18 个到期日**上，而那 18 个分两类没有第三类：
//	  疫情停夜盘窗口内 105 条 ｜ 端午/春节/中秋/春节【长假之后】88 条
//	对照：同一批日期到期的【有夜盘】合约 —— **0 条**
//	⇒ 读法是「这个合约最后一个交易日没有夜盘」，**而那是相关，不是上游文档**
type NightState int

// ⚠️ 从 1 起，**零值不是任何一种** —— 一个没被解出来的 Night 不该长得像 NightUnset。
// （同本仓 ClientUse 那一格：零值由校验拒，不给它一个「看起来合理」的含义。）
const (
	// NightUnset 是上游**没有 night 这个键**。全量 2321 条。
	NightUnset NightState = iota + 1
	// NightEmpty 是上游写了 `"night": []`。全量 193 条，**语义未知**。
	NightEmpty
	// NightRanges 是上游给了时段。全量 5157 条。
	NightRanges
)

func (s NightState) String() string {
	switch s {
	case NightUnset:
		return "unset"
	case NightEmpty:
		return "empty"
	case NightRanges:
		return "ranges"
	}
	return "?"
}

// Night 是夜盘那一格。
//
// ⚠️ 用一个显式的 State 而不是「`Ranges == nil` 就是没有」——
// 后者会把 NightUnset 与 NightEmpty 挤成同一个读数，**而那正是三态存在的理由**。
type Night struct {
	State  NightState
	Ranges []Range // 只有 State == NightRanges 时非空
}
